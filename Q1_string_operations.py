# Q1. String operations and methods

text = input("Enter a sentence: ")
print("Length:", len(text))
print("Uppercase:", text.upper())
print("Lowercase:", text.lower())
print("Trimmed:", text.strip())
old_word = input("Word to replace: ")
new_word = input("Replacement word: ")
print("Replaced sentence:", text.replace(old_word, new_word))
character = input("Character to count: ")
print("Occurrences:", text.count(character))
start_text = input("Substring to check at start: ")
end_text = input("Substring to check at end: ")
print("Starts with:", text.startswith(start_text))
print("Ends with:", text.endswith(end_text))
print("Concatenation:", text + " - Python")
print("Repetition:", text * 2)
word = input("Word to check membership: ")
print("Word present:", word in text)
